"""Build agent/land.py from the map's coastline (web/public/geo/land.geojson). Owner: B, for A.

    uv run python -m world.make_land

The agent never reads files at run time (no I/O on the boat), so the coastline is baked into a
Python module of integer local metres:
- OBSTACLES: land grown by CLEAR_M (a safety margin) and simplified, one ring per island or coast,
  clipped to the scene plus a margin.
- NODES: water waypoints NODE_M off the coast (corners of land grown by NODE_M), outside every
  obstacle.
- EDGES: for each node, the nodes it can see in a straight line without touching an obstacle,
  with the distance. Computed with agent/water.py's own integer test, so planning on the boat
  agrees with this table.
Run it again whenever land.geojson changes; tests/agent/test_water.py checks the module is fresh.
"""

import hashlib
import json
from pathlib import Path

from shapely.geometry import Polygon, box
from shapely.ops import unary_union

from contract.geo import dist, to_xy

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web/public/geo/land.geojson"
OUT = ROOT / "agent/land.py"
CLEAR_M = 50  # obstacle = land grown by this much: boats keep at least this far off the coast
NODE_M = 150  # waypoints sit this far off the coast
SIMPLIFY_M = 30
NODE_SIMPLIFY_M = 80
MARGIN_M = 4000  # around the mission's points


def _rings(geom) -> list[list[tuple[int, int]]]:
    geoms = getattr(geom, "geoms", [geom])
    out = []
    for g in geoms:
        if g.geom_type != "Polygon" or g.is_empty:
            continue
        ring = [(round(x), round(y)) for x, y in g.exterior.coords]
        if len(ring) >= 4:
            out.append(ring)
    return sorted(out)


def build() -> str:
    from agent import water  # the runtime test, so the table matches what the boat computes
    from world.routes import load_scene

    raw = SRC.read_bytes()
    mission = load_scene(ROOT).mission
    pts = [p for t in mission.tasks for p in t.pts] + [mission.shore]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    win = box(min(xs) - MARGIN_M, min(ys) - MARGIN_M, max(xs) + MARGIN_M, max(ys) + MARGIN_M)
    land = unary_union([Polygon([to_xy(lat, lon) for lon, lat in f["geometry"]["coordinates"][0]])
                        for f in json.loads(raw)["features"]])
    obstacles = _rings(land.buffer(CLEAR_M).simplify(SIMPLIFY_M).intersection(win))
    node_rings = _rings(land.buffer(NODE_M).simplify(NODE_SIMPLIFY_M).intersection(win))
    water.load(tuple(tuple(r) for r in obstacles), (), ())
    wx0, wy0, wx1, wy1 = (round(v) for v in win.bounds)
    nodes = sorted({p for r in node_rings for p in r[:-1]
                    if wx0 < p[0] < wx1 and wy0 < p[1] < wy1 and not water.on_land(p)})
    edges = []
    for i, a in enumerate(nodes):
        row = [(j, dist(a, b)) for j, b in enumerate(nodes) if j != i and not water.blocked(a, b)]
        edges.append(tuple(row))
    lines = [
        '"""Generated by world/make_land.py from web/public/geo/land.geojson. Do not edit.',
        "",
        "© OpenStreetMap contributors, ODbL (natural=coastline, prepared by tools/prepare_coastline.py).",
        f"Land grown by {CLEAR_M} m (obstacles); waypoints {NODE_M} m off the coast. Integer local metres.",
        '"""',
        f'SOURCE_SHA256 = "{hashlib.sha256(raw).hexdigest()}"',
        f"CLEAR_M = {CLEAR_M}",
        f"OBSTACLES = {tuple(tuple(r) for r in obstacles)!r}",
        f"NODES = {tuple(nodes)!r}",
        f"EDGES = {tuple(edges)!r}",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")
