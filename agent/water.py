"""Water-only routing around the real coastline. Owner: A.

The coastline comes from agent/land.py (generated by world/make_land.py from the map's
land.geojson, grown by a safety margin). Integer maths only, no clock, no randomness, so every
boat plans the same way on every run.

- blocked(a, b): the straight line a-b touches land. A point on land itself (the quay at Korsør,
  a cable's landfall) may leave or reach its own coast: crossings of the land it stands on within
  EXIT_M of it do not count.
- path(a, b): [a, ..., b], straight when clear, else the shortest chain over the water
  waypoints (Dijkstra over a precomputed visibility table).
"""

from heapq import heappop, heappush
from itertools import pairwise

from contract.geo import dist

Point = tuple[int, int]
EXIT_M = 120  # a boat on land (quay 90 m, landfall 65 m inside the margin) may cross its own coast this far

OBSTACLES: tuple[tuple[Point, ...], ...] = ()
NODES: tuple[Point, ...] = ()
EDGES: tuple[tuple[tuple[int, int], ...], ...] = ()
BOXES: tuple[tuple[int, int, int, int], ...] = ()


def load(obstacles, nodes, edges) -> None:
    global OBSTACLES, NODES, EDGES, BOXES
    OBSTACLES, NODES, EDGES = obstacles, nodes, edges
    BOXES = tuple((min(p[0] for p in r), min(p[1] for p in r), max(p[0] for p in r),
                   max(p[1] for p in r)) for r in obstacles)


try:
    from agent import land as _land

    load(_land.OBSTACLES, _land.NODES, _land.EDGES)
except ImportError:  # not generated yet: no land, every line is clear
    pass


def _cross(o: Point, a: Point, b: Point) -> int:
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def _inside(p: Point, ring: tuple[Point, ...]) -> bool:
    """Even-odd ray cast to +x, integer only."""
    x, y = p
    hit = False
    for (x1, y1), (x2, y2) in pairwise(ring):
        if (y1 > y) != (y2 > y):
            # x of the edge at height y, compared without division
            lhs = (x - x1) * (y2 - y1)
            rhs = (x2 - x1) * (y - y1)
            if (lhs < rhs) if y2 > y1 else (lhs > rhs):
                hit = not hit
    return hit


def on_land(p: Point) -> bool:
    return any(b[0] <= p[0] <= b[2] and b[1] <= p[1] <= b[3] and _inside(p, r)
               for r, b in zip(OBSTACLES, BOXES, strict=True))


def _hits(a: Point, b: Point, ring, near_a: bool, near_b: bool) -> bool:
    """Does a-b cross this ring, ignoring crossings within EXIT_M of an end standing on it?"""
    d = b[0] - a[0], b[1] - a[1]
    length = dist(a, b)
    lo_x, hi_x = min(a[0], b[0]), max(a[0], b[0])
    lo_y, hi_y = min(a[1], b[1]), max(a[1], b[1])
    for u, v in pairwise(ring):
        if (max(u[0], v[0]) < lo_x or min(u[0], v[0]) > hi_x
                or max(u[1], v[1]) < lo_y or min(u[1], v[1]) > hi_y):
            continue  # this coast edge is nowhere near the line
        d1, d2 = _cross(a, b, u), _cross(a, b, v)
        d3, d4 = _cross(u, v, a), _cross(u, v, b)
        if not ((d1 > 0) != (d2 > 0) and (d3 > 0) != (d4 > 0)):
            continue
        if near_a or near_b:
            # parameter t = num/den of the crossing along a-b
            e = v[0] - u[0], v[1] - u[1]
            den = d[0] * e[1] - d[1] * e[0]
            num = (u[0] - a[0]) * e[1] - (u[1] - a[1]) * e[0]
            if den < 0:
                num, den = -num, -den
            if near_a and num * length <= EXIT_M * den:
                continue
            if near_b and (den - num) * length <= EXIT_M * den:
                continue
        return True
    return False


def blocked(a: Point, b: Point) -> bool:
    lo_x, hi_x = min(a[0], b[0]), max(a[0], b[0])
    lo_y, hi_y = min(a[1], b[1]), max(a[1], b[1])
    for ring, bb in zip(OBSTACLES, BOXES, strict=True):
        if hi_x < bb[0] or lo_x > bb[2] or hi_y < bb[1] or lo_y > bb[3]:
            continue
        if _hits(a, b, ring, _inside(a, ring), _inside(b, ring)):
            return True
    return False


def _nearest(p: Point) -> list[int]:
    return [min(range(len(NODES)), key=lambda i: (dist(p, NODES[i]), i))] if NODES else []


def path(a: Point, b: Point) -> list[Point]:
    if a == b or not blocked(a, b):
        return [a, b]
    n = len(NODES)
    best: dict[int, int] = {}
    prev: dict[int, int] = {}
    heap: list[tuple[int, int]] = []
    starts = [i for i, p in enumerate(NODES) if not blocked(a, p)] or _nearest(a)
    for i in starts:
        best[i] = dist(a, NODES[i])
        prev[i] = -1
        heappush(heap, (best[i], i))
    # a point deep on land (a boat the current pushed onto the quay, a far landfall) sees no
    # waypoint: it leaves by, or arrives from, the nearest one rather than going straight
    ends = {i: dist(NODES[i], b) for i in ([i for i, p in enumerate(NODES) if not blocked(p, b)]
                                            or _nearest(b))}
    done: set[int] = set()
    goal, goal_d = -1, None
    while heap:
        d, i = heappop(heap)
        if i in done:
            continue
        done.add(i)
        if goal_d is not None and d >= goal_d:
            break
        if i in ends and (goal_d is None or d + ends[i] < goal_d):
            goal, goal_d = i, d + ends[i]
        for j, w in EDGES[i] if i < n else ():
            nd = d + w
            if nd < best.get(j, nd + 1):
                best[j], prev[j] = nd, i
                heappush(heap, (nd, j))
    if goal < 0:
        return [a, b]  # no water route known: straight, as before
    chain = []
    i = goal
    while i != -1:
        chain.append(NODES[i])
        i = prev[i]
    return [a, *reversed(chain), b]


_HOME: dict[Point, tuple[list[int], list[int]]] = {}  # home -> (distance, next node; -1 = home)


def _home_table(home: Point) -> tuple[list[int], list[int]]:
    """Shortest water distance from every waypoint to home, and its next hop (Dijkstra once)."""
    if home not in _HOME:
        n = len(NODES)
        best, nxt = [10**12] * n, [-2] * n
        heap: list[tuple[int, int]] = []
        for i, p in enumerate(NODES):
            if not blocked(p, home):
                best[i], nxt[i] = dist(p, home), -1
                heappush(heap, (best[i], i))
        done = [False] * n
        while heap:
            d, i = heappop(heap)
            if done[i]:
                continue
            done[i] = True
            for j, w in EDGES[i]:
                if d + w < best[j]:
                    best[j], nxt[j] = d + w, i
                    heappush(heap, (best[j], j))
        _HOME[home] = (best, nxt)
    return _HOME[home]


def home_path(a: Point, home: Point) -> list[Point]:
    """The water route from a to a fixed home point (the shore), same answer as path(a, home)
    but fast: the waypoints' distances home are computed once, and only the waypoints that could
    beat the best so far are checked for a clear line from a."""
    if a == home or not blocked(a, home):
        return [a, home]
    best, nxt = _home_table(home)
    order = sorted(range(len(NODES)), key=lambda i: (dist(a, NODES[i]) + best[i], i))
    pick = next((i for i in order if best[i] < 10**12 and not blocked(a, NODES[i])), None)
    if pick is None:
        pick = _nearest(a)[0] if NODES else None  # deep on land: leave by the nearest waypoint
    if pick is None or best[pick] >= 10**12:
        return [a, home]
    out = [a]
    i = pick
    while i >= 0:
        out.append(NODES[i])
        i = nxt[i]
    return [*out, home]


ACCESS_OUT_M = 25  # an access point sits this far outside the coast margin
_ACCESS: dict[Point, Point] = {}


def access(p: Point) -> Point:
    """Where a boat goes for a point that lies on land (a cable's landfall): the nearest point
    just outside the coast margin. A point in water is its own access point. A boat that aims at
    the landfall itself sees the line clear, then blocked, then clear again as it moves, and
    turns back and forth forever (seen at Sprogø); aiming here it simply arrives."""
    if p in _ACCESS:
        return _ACCESS[p]
    out = p
    if on_land(p):
        best: tuple[int, Point] | None = None
        for ring, bb in zip(OBSTACLES, BOXES, strict=True):
            if not (bb[0] <= p[0] <= bb[2] and bb[1] <= p[1] <= bb[3] and _inside(p, ring)):
                continue
            for u, v in pairwise(ring):
                ex, ey = v[0] - u[0], v[1] - u[1]
                den = ex * ex + ey * ey
                num = min(max((p[0] - u[0]) * ex + (p[1] - u[1]) * ey, 0), den) if den else 0
                q = (u[0] + ex * num // den, u[1] + ey * num // den) if den else u
                cand = (dist(p, q), q)
                if best is None or cand < best:
                    best = cand
        if best is not None:
            d, q = best
            for push in range(ACCESS_OUT_M, 10 * ACCESS_OUT_M + 1, ACCESS_OUT_M):
                out = (q[0] + (q[0] - p[0]) * push // max(d, 1), q[1] + (q[1] - p[1]) * push // max(d, 1))
                if not on_land(out):
                    break
    _ACCESS[p] = out
    return out


def arrive_m(p: Point, arrive: int) -> int:
    """How close counts as having reached p: as usual in water; for a point on land, as close
    as its access point plus the usual margin."""
    return arrive if not on_land(p) else dist(p, access(p)) + arrive


def nearest_node(p: Point) -> Point | None:
    """The nearest water waypoint with a clear line from p, else the nearest at all."""
    if not NODES:
        return None
    order = sorted(range(len(NODES)), key=lambda i: (dist(p, NODES[i]), i))
    for i in order[:12]:
        if not blocked(p, NODES[i]):
            return NODES[i]
    return NODES[order[0]]
